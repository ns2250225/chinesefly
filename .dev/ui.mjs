import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1440, height: 860 } })
p.on('pageerror', e => console.log('pageerror:', e.message))
p.on('console', m => { if (m.type()==='error') console.log('console:', m.text()) })
await p.goto('http://localhost:5173/'); await p.waitForTimeout(1500)
await p.screenshot({ path: '/tmp/u_title.png' })
await p.click('.start', { force: true }); await p.waitForTimeout(300)
const box = await p.locator('.fly-btn').boundingBox()
await p.mouse.move(box.x + box.width/2, box.y + box.height/2); await p.mouse.down()
await p.waitForTimeout(1200); await p.screenshot({ path: '/tmp/u_fly.png' })
await p.waitForTimeout(6000); await p.mouse.up()
await p.evaluate(() => window.__game.bus.emit('debug', 520000)); await p.waitForTimeout(400)
await p.keyboard.down('Space'); await p.waitForTimeout(4000); await p.screenshot({ path: '/tmp/u_absurd.png' }); await p.keyboard.up('Space')
await p.keyboard.press('Escape'); await p.waitForTimeout(500); await p.screenshot({ path: '/tmp/u_pause.png' })
await p.click('text=生成分享卡'); await p.waitForTimeout(600); await p.screenshot({ path: '/tmp/u_share.png' })
await p.click('.share .close'); await p.click('text=⚙ 设置'); await p.waitForTimeout(300); await p.screenshot({ path: '/tmp/u_settings.png' })
await p.click('text=完成'); await p.click('text=🎖 成就'); await p.waitForTimeout(300); await p.screenshot({ path: '/tmp/u_ach.png' })
await p.click('text=关闭'); await p.click('text=↻ 重新开始'); await p.waitForTimeout(800); await p.screenshot({ path: '/tmp/u_restart.png' })
console.log(await p.evaluate(() => window.__game.store.phase))
await b.close()
